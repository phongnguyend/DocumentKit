import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
const fixture = new URL('../../PptxObjectKit.Tests/Fixtures/sample.pptx', import.meta.url);

test('OCR recognizes locally, edits and moves lines, and applies editable slide text', async ({ page, request }, testInfo) => {
  test.setTimeout(120000);
  await page.goto('/');
  const encoded = await page.evaluate(() => {
    const canvas = document.createElement('canvas');
    canvas.width = 800;
    canvas.height = 240;
    const context = canvas.getContext('2d');
    context.fillStyle = 'white';
    context.fillRect(0, 0, 800, 240);
    context.fillStyle = 'black';
    context.font = '64px Arial';
    context.fillText('Hello OCR', 40, 100);
    context.fillText('Selected image text', 40, 190);
    return canvas.toDataURL().split(',')[1];
  });
  await page.getByLabel('Open PPTX', { exact: true }).setInputFiles({ name: 'ocr.pptx', mimeType: 'application/octet-stream', buffer: await readFile(fixture) });
  await page.getByRole('button', { name: 'Add image', exact: true }).click();
  await page.getByLabel('Image file').setInputFiles({ name: 'ocr.png', mimeType: 'image/png', buffer: Buffer.from(encoded, 'base64') });
  await page.getByLabel('Placement width').fill('400');
  await page.getByLabel('Placement height').fill('120');
  await page.getByRole('button', { name: 'Insert image', exact: true }).click();
  await expect(page.locator('.text-layer [data-kind="image"]')).toHaveCount(1);
  await page.locator('.inspector .object-list button').last().click();
  await page.getByRole('button', { name: 'Recognize text (OCR)' }).click();
  const dialog = page.getByRole('dialog', { name: 'Image OCR', exact: true });
  await expect(dialog.getByRole('img', { name: 'Extracted text canvas' })).toBeVisible({ timeout: 90000 });
  await dialog.getByRole('button', { name: 'Text', exact: true }).click();
  await expect(dialog.getByLabel('Extracted text')).toHaveValue(/Hello OCR/);
  await dialog.getByRole('button', { name: 'Canvas', exact: true }).click();
  await dialog.getByRole('button', { name: 'OCR line 1', exact: true }).click();
  await dialog.getByLabel('Selected OCR text').fill('Corrected OCR text');
  const line = dialog.getByRole('button', { name: 'OCR line 1', exact: true });
  const box = await line.boundingBox();
  await page.mouse.move(box.x + 10, box.y + 10);
  await page.mouse.down();
  await page.mouse.move(box.x + 25, box.y + 20, { steps: 4 });
  await page.mouse.up();
  await page.screenshot({ path: testInfo.outputPath('ocr.png') });
  await dialog.getByRole('button', { name: 'Apply to slide' }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.locator('.text-layer')).toContainText('Corrected OCR text');
  await expect(page.locator('.text-layer [data-kind="image"]')).toHaveCount(1);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.locator('.text-layer')).not.toContainText('Corrected OCR text');
  await page.locator('.inspector .object-list button').last().click();
  await page.getByRole('button', { name: 'Recognize text (OCR)' }).click();
  await expect(dialog.getByRole('img', { name: 'Extracted text canvas' })).toBeVisible({ timeout: 90000 });
  await dialog.getByLabel('OCR apply mode').selectOption('replace');
  await dialog.getByRole('button', { name: 'Apply to slide' }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.locator('.text-layer [data-kind="image"]')).toHaveCount(0);
  await expect(page.locator('.text-layer')).toContainText('Hello OCR');
  const saved = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download PPTX', exact: true }).click();
  const response = await request.post('/api/documents/inspect', { data: await readFile(await (await saved).path()) });
  expect(response.ok()).toBe(true);
  const result = await response.json();
  expect(result.slides[0].images).toHaveLength(0);
  expect(result.slides[0].textObjects.some(item => item.text.includes('Hello OCR'))).toBe(true);
});
