import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('image insert, drag, resize, replace, download, delete and undo survive XLSX round trips', async ({ page, request }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'New workbook', exact: true }).click();
  await page.getByRole('button', { name: 'Add image', exact: true }).click();
  const png = Buffer.from(await page.evaluate(() => {
    const canvas = document.createElement('canvas');
    canvas.width = 120;
    canvas.height = 80;
    const ctx = canvas.getContext('2d');
    ctx.fillStyle = 'red';
    ctx.fillRect(0, 0, 120, 80);
    return canvas.toDataURL().split(',')[1];
  }), 'base64');
  await page.getByLabel('Image file', { exact: true }).setInputFiles({ name: 'red.png', mimeType: 'image/png', buffer: png });
  await page.getByRole('button', { name: 'Insert image', exact: true }).click();
  const image = page.getByRole('button', { name: 'Select image Image 1', exact: true });
  await expect(image).toBeVisible();
  const before = await image.boundingBox();
  await page.mouse.move(before.x + 30, before.y + 30);
  await page.mouse.down();
  await page.mouse.move(before.x + 70, before.y + 60, { steps: 8 });
  await page.mouse.up();
  await expect(image).toHaveCSS('left', '88px');
  await expect(image).toHaveCSS('top', '62px');
  const handle = await image.locator('.se').boundingBox();
  await page.mouse.move(handle.x + 5, handle.y + 5);
  await page.mouse.down();
  await page.mouse.move(handle.x + 45, handle.y + 25, { steps: 8 });
  await page.mouse.up();
  await expect(image).toHaveCSS('width', '280px');
  await expect(image).toHaveCSS('height', '180px');
  await page.getByRole('button', { name: 'Replace image', exact: true }).click();
  await page.getByLabel('Image file', { exact: true }).setInputFiles({ name: 'replacement.png', mimeType: 'image/png', buffer: png });
  await page.getByRole('dialog').getByRole('button', { name: 'Replace image', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(image).toHaveCSS('width', '280px');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download XLSX', exact: true }).click();
  const bytes = await readFile(await (await download).path());
  const inspected = await request.post('/api/documents/inspect', { data: bytes });
  expect(inspected.ok()).toBeTruthy();
  expect((await inspected.json()).sheets[0].images[0]).toMatchObject({ x: 40, y: 30, width: 280, height: 180 });
  const exportedImage = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download image', exact: true }).click();
  expect(await readFile(await (await exportedImage).path())).toEqual(png);
  await image.focus();
  await page.keyboard.press('Delete');
  await expect(image).toHaveCount(0);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(image).toBeVisible();
});

test('image source offers drawing and QR generation', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'New workbook', exact: true }).click();
  await page.getByRole('button', { name: 'Add image', exact: true }).click();
  await page.getByRole('button', { name: 'Draw image', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Draw an image', exact: true })).toBeVisible();
  const canvas = await page.getByLabel('Drawing canvas', { exact: true }).boundingBox();
  await page.mouse.move(canvas.x + 20, canvas.y + 20);
  await page.mouse.down();
  await page.mouse.move(canvas.x + 70, canvas.y + 50, { steps: 6 });
  await page.mouse.up();
  await page.getByRole('button', { name: 'Use drawing', exact: true }).click();
  await page.getByRole('button', { name: 'Insert image', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Select image Image 1', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add image', exact: true }).click();
  await page.getByRole('button', { name: 'Generate QR code', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Generate QR code', exact: true })).toBeVisible();
  await page.getByLabel('QR content', { exact: true }).fill('https://example.org/');
  await page.getByRole('button', { name: 'Use QR code', exact: true }).click();
  await page.getByRole('button', { name: 'Insert image', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Select image Image 2', exact: true })).toBeVisible();
});
